"""Catálogo de exercícios com demonstração de execução.

Cada exercício traz: passo a passo da execução, pontos-chave (cues), erros comuns,
respiração, cadência padrão, restrições (usadas para adaptar a ficha às avaliações e
exames) e substitutos seguros. O campo `video_url` aponta para uma busca de vídeo de
demonstração do movimento.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from urllib.parse import quote_plus


@dataclass(frozen=True)
class Exercise:
    id: str
    name: str
    pattern: str
    muscles: list[str]
    equipment: str
    level: int  # 1 iniciante, 2 intermediário, 3 avançado
    steps: list[str]
    cues: list[str]
    mistakes: list[str]
    breathing: str = "Expire na fase concêntrica (esforço) e inspire na excêntrica (retorno)."
    tempo: str = "2-0-1-1"  # excêntrica-pausa embaixo-concêntrica-pausa em cima (s)
    restrictions: list[str] = field(default_factory=list)
    alternatives: list[str] = field(default_factory=list)
    is_cardio: bool = False
    met_key: str | None = None

    @property
    def video_url(self) -> str:
        return "https://www.youtube.com/results?search_query=" + quote_plus(
            f"{self.name} execução correta"
        )

    def to_dict(self) -> dict:
        return {
            "id": self.id,
            "name": self.name,
            "pattern": self.pattern,
            "muscles": self.muscles,
            "equipment": self.equipment,
            "level": self.level,
            "is_cardio": self.is_cardio,
            "demonstration": {
                "steps": self.steps,
                "cues": self.cues,
                "common_mistakes": self.mistakes,
                "breathing": self.breathing,
                "tempo": self.tempo,
                "tempo_legend": "excêntrica - pausa embaixo - concêntrica - pausa em cima (segundos)",
                "video_url": self.video_url,
            },
            "restrictions": self.restrictions,
            "alternatives": self.alternatives,
        }


